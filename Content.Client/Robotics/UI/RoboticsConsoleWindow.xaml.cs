using Content.Client.Stylesheets;
using Content.Client.UserInterface.Controls;
using Content.Shared.Lock;
using Content.Shared.Robotics;
using Content.Shared.Robotics.Components;
using Robust.Client.AutoGenerated;
using Robust.Client.GameObjects;
using Robust.Client.UserInterface.XAML;
using System.Linq;
using Robust.Client.Graphics;
using Robust.Shared.Prototypes;
using Robust.Shared.Timing;
using Robust.Shared.Utility;

namespace Content.Client.Robotics.UI;

[GenerateTypedNameReferences]
public sealed partial class RoboticsConsoleWindow : FancyWindow
{
    [Dependency] private readonly IEntityManager _entMan = default!;
    [Dependency] private readonly IGameTiming _timing = default!;
    private readonly LockSystem _lock;
    private readonly SpriteSystem _sprite;

    public Action<string>? OnChangeLawsPressed; // Corvax-Goob-MutableLaws
    public Action<string>? OnDisablePressed;
    public Action<string>? OnDestroyPressed;

    // CorvaxGoob-Pulsar-Start
    public Action<string, bool>? OnPulsarLinkPressed;
    public Action<NetEntity, bool>? OnMinibotLinkPressed;
    private NetEntity? _selectedMinibot;
    private List<RoboticsMinibotData> _minibots = new();
    private bool _pulsarAvailable;
    // CorvaxGoob-Pulsar-End

    private string? _selected;
    private Dictionary<string, CyborgControlData> _cyborgs = new();

    public EntityUid Entity;

    private bool _allowBorgControl = true;

    public RoboticsConsoleWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        _lock = _entMan.System<LockSystem>();
        _sprite = _entMan.System<SpriteSystem>();

        Cyborgs.OnItemSelected += args =>
        {
            if (Cyborgs[args.ItemIndex].Metadata is not string address)
                return;

            _selected = address;
            PopulateData();
        };
        Cyborgs.OnItemDeselected += _ =>
        {
            _selected = null;
            PopulateData();
        };

        // these won't throw since buttons are only visible if a borg is selected
        // Corvax-Goob-MutableLaws-Start
        ChangeLawsButton.OnPressed += _ =>
        {
            OnChangeLawsPressed?.Invoke(_selected!);
        };
        // Corvax-Goob-MutableLaws-End
        DisableButton.OnPressed += _ =>
        {
            OnDisablePressed?.Invoke(_selected!);
        };
        DestroyButton.OnPressed += _ =>
        {
            OnDestroyPressed?.Invoke(_selected!);
        };

        // cant put multiple styles in xaml for some reason
        DestroyButton.StyleClasses.Add(StyleClass.Negative);

        // CorvaxGoob-Pulsar-Start
        Tabs.SetTabTitle(0, Loc.GetString("robotics-console-tab-units"));
        Tabs.SetTabTitle(1, Loc.GetString("robotics-console-tab-minibots"));

        PulsarLinkButton.OnPressed += _ =>
        {
            if (_selected is { } address && _cyborgs.TryGetValue(address, out var data))
                OnPulsarLinkPressed?.Invoke(address, !data.PulsarLinked);
        };

        Minibots.OnItemSelected += args =>
        {
            if (Minibots[args.ItemIndex].Metadata is not NetEntity bot)
                return;
            _selectedMinibot = bot;
            PopulateMinibotData();
        };
        Minibots.OnItemDeselected += _ =>
        {
            _selectedMinibot = null;
            PopulateMinibotData();
        };

        MinibotLinkButton.OnPressed += _ =>
        {
            if (SelectedMinibot() is { } bot)
                OnMinibotLinkPressed?.Invoke(bot.Entity, !bot.Linked);
        };
        // CorvaxGoob-Pulsar-End
    }

    public void SetEntity(EntityUid uid)
    {
        Entity = uid;
    }

    public void UpdateState(RoboticsConsoleState state)
    {
        _cyborgs = state.Cyborgs;
        _allowBorgControl = state.AllowBorgControl;
        _pulsarAvailable = state.PulsarAvailable; // CorvaxGoob-Pulsar

        // clear invalid selection
        if (_selected is {} selected && !_cyborgs.ContainsKey(selected))
            _selected = null;

        // Corvax-Next-AiRemoteControl-Start
        var isAiControllable = false;
        var isLawChangable = false; // CorvaxGoob-MutableLaws

        if (_selected != null)
        {
            _cyborgs.TryGetValue(_selected, out var data);
            isAiControllable = data.IsAiControllable;
            isLawChangable = data.IsLawChangable; // Corvax-Goob-MutableLaws
        }
        // Corvax-Next-AiRemoteControl-End

        var hasCyborgs = _cyborgs.Count > 0;
        NoCyborgs.Visible = !hasCyborgs;
        CyborgsContainer.Visible = hasCyborgs;
        ChangeLawsButton.Disabled = !state.HasCircuitBoard || !isLawChangable; // Corvax-Goob-MutableLaws
        PopulateCyborgs();

        PopulateData();

        var locked = _lock.IsLocked(Entity);
        DangerZone.Visible = !locked && _allowBorgControl;
        LockedMessage.Visible = locked && (_allowBorgControl || state.PulsarAvailable); // Only show if locked AND control is allowed

        // CorvaxGoob-Pulsar-Start
        _minibots = state.Minibots;
        if (_selectedMinibot is { } sel && _minibots.All(m => m.Entity != sel))
            _selectedMinibot = null;
        NoMinibots.Visible = _minibots.Count == 0;
        MinibotsContainer.Visible = _minibots.Count > 0;
        PopulateMinibots();
        PopulateMinibotData();
        // CorvaxGoob-Pulsar-End
    }

    // CorvaxGoob-Pulsar-Start
    private RoboticsMinibotData? SelectedMinibot()
    {
        return _selectedMinibot is { } sel ? _minibots.FirstOrDefault(m => m.Entity == sel) : null;
    }

    private Texture? MinibotIcon(RoboticsMinibotData bot)
    {
        var protoMan = IoCManager.Resolve<IPrototypeManager>();
        return protoMan.TryIndex<EntityPrototype>(bot.Prototype, out var proto) ? _sprite.Frame0(proto) : null;
    }

    private void PopulateMinibots()
    {
        var selected = _selectedMinibot;
        Minibots.Clear();
        foreach (var bot in _minibots)
        {
            var item = Minibots.AddItem(bot.Linked ? $"{bot.Name} ◆" : bot.Name, MinibotIcon(bot), metadata: bot.Entity);
            item.Selected = bot.Entity == selected;
        }
        _selectedMinibot = selected;
    }

    private void PopulateMinibotData()
    {
        if (SelectedMinibot() is not { } bot)
        {
            SelectMinibot.Visible = true;
            MinibotContainer.Visible = false;
            return;
        }

        SelectMinibot.Visible = false;
        MinibotContainer.Visible = true;
        MinibotSprite.Texture = MinibotIcon(bot);

        var hpColor = HealthColor(bot.HpPercent);
        var text = new FormattedMessage();
        text.AddMarkupOrThrow($"{Loc.GetString("robotics-console-minibot-kind", ("kind", bot.Kind))}\n");
        text.AddMarkupOrThrow(Loc.GetString("robotics-console-designation"));
        text.AddText($" {bot.Name}\n");
        text.AddMarkupOrThrow($"{Loc.GetString("robotics-console-hp", ("hp", (int) (bot.HpPercent * 100f)), ("color", hpColor))}\n");
        if (bot.Anchored)
            text.AddMarkupOrThrow($"{Loc.GetString("robotics-console-minibot-anchored")}\n");
        text.AddMarkupOrThrow(Loc.GetString("robotics-console-pulsar-state",
            ("state", bot.Linked ? FormattedMessage.EscapeText(bot.Task) : Loc.GetString("robotics-console-pulsar-state-off"))));
        MinibotInfo.SetMessage(text);

        var locked = _lock.IsLocked(Entity);
        MinibotPulsarBox.Visible = !locked && _pulsarAvailable;
        MinibotLockedMessage.Visible = locked;
        MinibotLinkButton.Text = Loc.GetString(bot.Linked ? "robotics-console-pulsar-unlink" : "robotics-console-pulsar-link");
        MinibotLinkButton.Disabled = !bot.Linked && bot.Anchored;
    }

    private static string HealthColor(float hp) => hp switch
    {
        < 0.2f => "#FF6C7F",
        < 0.4f => "#EF973C",
        < 0.6f => "#E8CB2D",
        < 0.8f => "#30CC19",
        _ => "#00D3B8",
    };
    // CorvaxGoob-Pulsar-End

    private void PopulateCyborgs()
    {
        // _selected might get set to null when recreating so copy it first
        var selected = _selected;
        Cyborgs.Clear();
        foreach (var (address, data) in _cyborgs)
        {
            var item = Cyborgs.AddItem(data.PulsarLinked ? $"{data.Name} ◆" : data.Name, _sprite.Frame0(data.ChassisSprite!), metadata: address); // CorvaxGoob-Pulsar: ◆ = linked to the AI
            item.Selected = address == selected;
        }
        _selected = selected;
    }

    private void PopulateData()
    {
        if (_selected is not {} selected)
        {
            SelectCyborg.Visible = true;
            BorgContainer.Visible = false;
            return;
        }

        SelectCyborg.Visible = false;
        BorgContainer.Visible = true;

        var data = _cyborgs[selected];
        var model = data.ChassisName;

        BorgSprite.Texture = _sprite.Frame0(data.ChassisSprite!);

        var batteryColor = data.Charge switch {
            < 0.2f => "#FF6C7F", // red
            < 0.4f => "#EF973C", // orange
            < 0.6f => "#E8CB2D", // yellow
            < 0.8f => "#30CC19", // green
            _ => "#00D3B8" // cyan
        };

        var hpPercentColor = data.HpPercent switch {
            < 0.2f => "#FF6C7F", // red
            < 0.4f => "#EF973C", // orange
            < 0.6f => "#E8CB2D", // yellow
            < 0.8f => "#30CC19", // green
            _ => "#00D3B8" // cyan
        };

        var text = new FormattedMessage();
        text.AddMarkupOrThrow($"{Loc.GetString("robotics-console-model", ("name", model))}\n");
        text.AddMarkupOrThrow(Loc.GetString("robotics-console-designation"));
        text.AddText($" {data.Name}\n"); // prevent players trolling by naming borg [color=red]satan[/color]
        text.AddMarkupOrThrow($"{Loc.GetString("robotics-console-battery", ("charge", (int)(data.Charge * 100f)), ("color", batteryColor))}\n");
        text.AddMarkupOrThrow($"{Loc.GetString("robotics-console-hp", ("hp", (int)(data.HpPercent * 100f)), ("color", hpPercentColor))}\n");
        text.AddMarkupOrThrow($"{Loc.GetString("robotics-console-brain", ("brain", data.HasBrain))}\n");
        text.AddMarkupOrThrow(Loc.GetString("robotics-console-modules", ("count", data.ModuleCount)));
        // CorvaxGoob-Pulsar-Start
        if (data.PulsarLinkable)
        {
            text.AddMarkupOrThrow("\n" + Loc.GetString("robotics-console-pulsar-state",
                ("state", data.PulsarLinked ? FormattedMessage.EscapeText(data.PulsarTask) : Loc.GetString("robotics-console-pulsar-state-off"))));
        }

        PulsarBox.Visible = data.PulsarLinkable && _pulsarAvailable && !_lock.IsLocked(Entity);
        PulsarLinkButton.Text = Loc.GetString(data.PulsarLinked ? "robotics-console-pulsar-unlink" : "robotics-console-pulsar-link");
        // CorvaxGoob-Pulsar-End
        BorgInfo.SetMessage(text);

        // how the turntables
        DisableButton.Disabled = !_allowBorgControl || !(data.HasBrain && data.CanDisable);
        DestroyButton.Disabled = !_allowBorgControl;
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);

        if (_entMan.TryGetComponent(Entity, out RoboticsConsoleComponent? console))
        {
            DestroyButton.Disabled = _timing.CurTime < console.NextDestroy;
        }
        else
        {
            DestroyButton.Disabled = true;
        }
    }
}
