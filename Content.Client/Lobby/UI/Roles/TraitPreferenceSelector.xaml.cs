using Robust.Shared.Utility;

namespace Content.Client.Lobby.UI.Roles;

[GenerateTypedNameReferences]
public sealed partial class TraitPreferenceSelector : Control
{
    public TraitPrototype Trait { get; }

    public bool Valid;
    private bool _showUnusable;

    public bool ShowUnusable
    {
        get => _showUnusable;
        set
        {
            _showUnusable = value;
            Visible = Valid || _showUnusable || Preference;
            PreferenceButton.RemoveStyleClass(StyleClass.Negative);
            if (!Valid)
                PreferenceButton.AddStyleClass(StyleClass.Negative);
        }
    }

    public bool Preference
    {
        get => PreferenceButton.Pressed;
        set => PreferenceButton.Pressed = value;
    }

    public event Action<bool>? PreferenceChanged;

    public TraitPreferenceSelector(
        TraitPrototype trait,
        JobPrototype? highJob,
        HumanoidCharacterProfile profile,
        IEntityManager entityManager,
        IPrototypeManager prototypeManager,
        IConfigurationManager configManager)
    {
        RobustXamlLoader.Load(this);

        Trait = trait;

        var name = TraitPrototype.GetName(trait);
        PreferenceButton.AddChild(new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Horizontal,
            Children =
            {
                new Label
                {
                    Text = trait.Points.ToString(),
                    StyleClasses = { StyleNano.StyleClassLabelHeading },
                    MinWidth = 32,
                    MaxWidth = 32,
                    ClipText = true,
                    Margin = new Thickness(0, 0, 8, 0),
                },
                new Label
                {
                    Text = name,
                    Margin = new Thickness(8, 0, 0, 0),
                },
            },
        });
        PreferenceButton.OnToggled += _ => PreferenceChanged?.Invoke(Preference);

        var tooltip = new Tooltip();
        PreferenceButton.TooltipSupplier = _ => tooltip;

        var desc = TraitPrototype.GetDescription(trait) ?? string.Empty;
        CharacterRequirementsSystem.CheckRequirementsValid(
            trait.Requirements,
            highJob,
            profile,
            new Dictionary<string, TimeSpan>(),
            true,
            trait,
            entityManager,
            prototypeManager,
            configManager,
            out var reasons);

        var markup = new FormattedMessage();
        if (!string.IsNullOrEmpty(desc))
            markup.AddMarkupPermissive(desc);
        if (reasons.Count > 0)
        {
            if (!markup.IsEmpty)
                markup.PushNewline();
            markup.AddMarkupPermissive(Loc.GetString("character-requirement-desc"));
            markup.PushNewline();
            markup.AddMarkupPermissive(CharacterRequirementsSystem.GetRequirementsMarkup(reasons));
        }

        if (!markup.IsEmpty)
            tooltip.SetMessage(markup);
    }
}
